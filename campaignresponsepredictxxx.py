import pickle
import numpy as np
import pandas as pd
import warnings
import io
import plotly.express as px
import plotly.graph_objects as go
from sklearn.metrics import roc_auc_score
import streamlit as st

warnings.filterwarnings('ignore')

# Load model
with open("Train_model.pkl", "rb") as f:
    (xgb, feature_columns) = pickle.load(f)

# --- Data Processing and Feature Engineering Function ---
def process_customer_data(retail_df, response_df):
    # 1. Online Retail Sales Data Cleaning and Feature Engineering
    retail_df['InvoiceDate'] = pd.to_datetime(retail_df['InvoiceDate'], dayfirst=True)
    retail_df = retail_df.drop_duplicates()
    retail_df = retail_df.replace(r'^\s*$', pd.NA, regex=True)
    retail_df = retail_df.dropna()

    if not pd.api.types.is_numeric_dtype(retail_df['Quantity']) or not pd.api.types.is_numeric_dtype(retail_df['UnitPrice']):
        raise ValueError("Both 'Quantity' and 'UnitPrice' must be numeric.")

    retail_df = retail_df[retail_df['Quantity'] >= 0]
    retail_df['Total'] = retail_df['Quantity'] * retail_df['UnitPrice']

    total_sales_per_customer = retail_df.groupby('CustomerID')['Total'].sum().reset_index(name='Total_Sales')
    unique_products_per_customer = retail_df.groupby('CustomerID')['StockCode'].nunique().reset_index(name='UniqueProductPurchased')
    invoices_generated_per_customer = retail_df.groupby('CustomerID')['InvoiceNo'].nunique().reset_index(name='Num_Invoices')

    latest_date = retail_df['InvoiceDate'].max()
    customer_recency = retail_df.groupby('CustomerID')['InvoiceDate'].max().reset_index()
    customer_recency['RecencyDays'] = (latest_date - customer_recency['InvoiceDate']).dt.days

    rfm = total_sales_per_customer.merge(invoices_generated_per_customer, on='CustomerID') \
                .merge(customer_recency[['CustomerID','RecencyDays']],on='CustomerID') \
                .merge(unique_products_per_customer,on='CustomerID')

    # 2. Campaign Response Data Cleaning
    response_df = response_df.drop_duplicates()
    response_df = response_df.replace(r'^\s*$', pd.NA, regex=True)
    response_df = response_df.dropna()
    response_df['nps'] = response_df['nps'].astype('int64')

    # 3. Merge dataframes
    masterdata = pd.merge(response_df, rfm, how='left', on='CustomerID')
    masterdata = masterdata.dropna()

    # Ensure correct dtypes
    masterdata['nps'] = masterdata['nps'].astype(np.int64)
    masterdata['Num_Invoices'] = masterdata['Num_Invoices'].astype(np.int64)
    masterdata['RecencyDays'] = masterdata['RecencyDays'].astype(np.int64)
    masterdata['UniqueProductPurchased'] = masterdata['UniqueProductPurchased'].astype(np.int64)
    masterdata['loyalty'] = masterdata['loyalty'].astype(np.int64)
    return masterdata

# --- Streamlit UI Setup ---
st.set_page_config(layout="wide")
st.title("Customer Response Campaign Dashboard")

col1, col2 = st.columns(2)
with col1:
    retail_file = st.file_uploader("Select Retail Sales Data (CSV/EXCEL)", type=['csv', 'xlsx', 'xls'])
with col2:
    response_file = st.file_uploader("Select Campaign Response Data (CSV/EXCEL)", type=['csv', 'xlsx', 'xls'])

if retail_file and response_file:
    if st.button("Process Data", type="primary"):
        try:
            if retail_file.name.endswith('.csv'):
                retail_df = pd.read_csv(retail_file)
            else:
                retail_df = pd.read_excel(retail_file)

            if response_file.name.endswith('.csv'):
                response_df = pd.read_csv(response_file)
            else:
                response_df = pd.read_excel(response_file)

            with st.spinner("Processing customer data and generating predictions..."):
                masterdata = process_customer_data(retail_df, response_df)

                X_test = masterdata[feature_columns]
                masterdata['prediction_proba'] = xgb.predict_proba(X_test)[:, 1]

                st.session_state['masterdata'] = masterdata
                st.success("Data successfully processed!")
        except Exception as e:
            st.error(f"Error during data processing: {e}")

if 'masterdata' in st.session_state:
    masterdata = st.session_state['masterdata']

    threshold = st.slider(
        "Adjust threshold to filter predictions:",
        min_value=0.0,
        max_value=1.0,
        value=0.5,
        step=0.05
    )

    masterdata['predicted_response'] = (masterdata['prediction_proba'] >= threshold).astype(int)
    response_counts = masterdata['predicted_response'].value_counts().reindex([0, 1], fill_value=0)
    respondents = response_counts[1]
    non_respondents = response_counts[0]
    total_customers = len(masterdata)
    response_rate = (respondents / total_customers) * 100 if total_customers > 0 else 0

    try:
        auc_val = roc_auc_score(masterdata['response'], masterdata['prediction_proba'])
        auc_text = f"{auc_val:.4f}"
    except Exception as e:
        auc_text = "N/A"

    st.markdown("---")

    metrics_col, chart_col = st.columns(2)
    with metrics_col:
        st.subheader("Prediction Summary")
        st.metric("Total Customers", f"{total_customers:,}")
        st.metric("Predicted Respondents", f"{respondents:,}")
        st.metric("Predicted Non-Respondents", f"{non_respondents:,}")
        st.metric("Predicted Response Rate", f"{response_rate:.2f}%")
        st.metric("AUC Score", auc_text)

    with chart_col:
        pie_data = pd.DataFrame({
            'Category': ['Responded', 'Not Responded'],
            'Count': [respondents, non_respondents]
        })
        pie_chart = px.pie(pie_data, names='Category', values='Count', title='Campaign Response Rate',
                           color_discrete_map={'Responded': 'green', 'Not Responded': 'red'})
        st.plotly_chart(pie_chart, use_container_width=True)

    st.markdown("---")

    imp_col, pred_col = st.columns(2)
    with imp_col:
        st.subheader("Model Feature Importance")
        feature_importance_df = pd.DataFrame({
            'Feature': feature_columns,
            'Importance': xgb.feature_importances_
        }).sort_values(by='Importance', ascending=False)

        feature_importance_chart = px.bar(feature_importance_df,
                                          x='Importance',
                                          y='Feature',
                                          orientation='h',
                                          title='Feature Importance for Response Prediction',
                                          labels={'Importance': 'Importance Score', 'Feature': 'Feature Name'})
        feature_importance_chart.update_layout(yaxis={'categoryorder':'total ascending'})
        st.plotly_chart(feature_importance_chart, use_container_width=True)
        st.dataframe(feature_importance_df, use_container_width=True)

    with pred_col:
        st.subheader("Customer Predictions")
        prediction_table_data = masterdata[['CustomerID', 'prediction_proba', 'predicted_response']].sort_values(by='prediction_proba', ascending=False)
        filtered_table_data = prediction_table_data[prediction_table_data['predicted_response'] == 1]

        if not filtered_table_data.empty:
            st.dataframe(filtered_table_data.head(10), use_container_width=True)
        else:
            st.write(f"No customers predicted to respond at a threshold of {threshold}.")